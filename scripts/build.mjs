/* Builds the deployable site in dist/.
 *
 * GitHub Pages only serves static files, so the build:
 *   1. copies site/ verbatim (it already uses relative URLs, which is what
 *      makes the same output work at /, /<repo>/ or a custom domain);
 *   2. copies the pinned Scramjet / controller / transport bundles out of
 *      node_modules — nothing is fetched at runtime;
 *   3. writes relay-config.js with the Wisp endpoint pool;
 *   4. points 404.html at the site's real base URL.
 *
 * The source tree is never modified, so `npm run dev` keeps working.
 */
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(SCRIPT_DIR, "..");
export const SITE_DIR = path.join(ROOT, "site");
export const DEFAULT_OUT_DIR = path.join(ROOT, "dist");

export const DEFAULT_WISP_ENDPOINTS = Object.freeze([
  "wss://wisp.webmc.fun/",
  "wss://wisp.freewisp.org/",
  "wss://wisp.mercurywork.shop/",
  "wss://wisp.terbiumon.top/wisp/",
  "wss://anura.pro/",
]);

/* [source in node_modules, destination in dist] — also used by the dev
 * server to mount the same bundles without a build step.
 *
 * Note: libcurl-transport@2 embeds its WASM as a base64 data URI, so
 * libcurl.js's separate .wasm file is deliberately not shipped. */
export const BUNDLE_FILES = Object.freeze([
  ["node_modules/@mercuryworkshop/scramjet/dist/scramjet.js", "scram/scramjet.js"],
  ["node_modules/@mercuryworkshop/scramjet/dist/scramjet.wasm", "scram/scramjet.wasm"],
  ["node_modules/@mercuryworkshop/scramjet-utils/dist/scramjet-utils.js", "scram/scramjet-utils.js"],
  ["node_modules/@mercuryworkshop/scramjet-controller/dist/controller.api.js", "controller/controller.api.js"],
  ["node_modules/@mercuryworkshop/scramjet-controller/dist/controller.inject.js", "controller/controller.inject.js"],
  ["node_modules/@mercuryworkshop/scramjet-controller/dist/controller.sw.js", "controller/controller.sw.js"],
  ["node_modules/@mercuryworkshop/libcurl-transport/dist/index.js", "clients/libcurl-client.js"],
  ["node_modules/@mercuryworkshop/epoxy-transport/dist/index.js", "clients/epoxy-client.js"],
  ["node_modules/@mercuryworkshop/epoxy-tls/full/epoxy.wasm", "clients/epoxy.wasm"],
]);

export function normaliseWisp(value) {
  const raw = String(value || "").trim();
  if (!raw) return "";
  const hasScheme = /^[a-z][a-z0-9+.-]*:/i.test(raw);
  const url = new URL(hasScheme ? raw : `wss://${raw}`);
  if (url.protocol !== "ws:" && url.protocol !== "wss:")
    throw new Error(`Invalid Wisp URL (expected ws:// or wss://): ${value}`);
  if (!url.pathname.endsWith("/")) url.pathname += "/";
  return url.href;
}

export function wispFromEnv(env = process.env) {
  const override = String(env.RELAY_WISP || "")
    .split(",")
    .map((v) => v.trim())
    .filter(Boolean)
    .map(normaliseWisp);
  return Object.freeze(override.length ? [...new Set(override)] : [...DEFAULT_WISP_ENDPOINTS]);
}

/** Absolute URL of the deployed site, used by 404.html. */
export function siteUrlFromEnv(env = process.env) {
  if (env.RELAY_BASE_URL) return String(env.RELAY_BASE_URL).replace(/\/?$/, "/");
  const repo = env.GITHUB_REPOSITORY; // "owner/name"
  if (repo && repo.includes("/")) {
    const [owner, name] = repo.split("/");
    if (owner && name) return `https://${owner}.github.io/${name}/`;
  }
  return "";
}

async function requireFile(file, label) {
  try {
    const info = await stat(file);
    if (!info.isFile()) throw new Error("not a file");
    return info;
  } catch {
    throw new Error(`Missing ${label}: ${file}. Run npm ci --ignore-scripts first.`);
  }
}

export async function build({
  root = ROOT,
  outDir = DEFAULT_OUT_DIR,
  wisp = wispFromEnv(),
  siteUrl = siteUrlFromEnv(),
} = {}) {
  const siteDir = path.join(root, "site");
  await requireFile(path.join(siteDir, "index.html"), "site entry point");
  for (const [from] of BUNDLE_FILES) await requireFile(path.join(root, from), "proxy bundle");

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await cp(siteDir, outDir, { recursive: true });

  let bundleBytes = 0;
  for (const [from, to] of BUNDLE_FILES) {
    const dest = path.join(outDir, to);
    await mkdir(path.dirname(dest), { recursive: true });
    await cp(path.join(root, from), dest);
    bundleBytes += (await stat(dest)).size;
  }

  const config = [
    "/* Generated by scripts/build.mjs — do not edit. */",
    `window.RELAY_WISP = ${JSON.stringify(wisp, null, 2)};`,
    `window.RELAY_BUILD = ${JSON.stringify({
      built: new Date().toISOString(),
      commit: process.env.GITHUB_SHA || "",
      siteUrl: siteUrl || null,
    }, null, 2)};`,
    "",
  ].join("\n");
  await writeFile(path.join(outDir, "relay-config.js"), config);

  // relay-config.js must load before the app module.
  const indexPath = path.join(outDir, "index.html");
  const html = await readFile(indexPath, "utf8");
  const appTag = '<script type="module" src="js/app.js"></script>';
  if (!html.includes(appTag)) throw new Error("Could not find the app script tag in site/index.html");
  await writeFile(
    indexPath,
    html.replace(appTag, `<script src="relay-config.js"></script>\n    ${appTag}`),
  );

  // replaceAll, not replace: the placeholder also appears in an explanatory
  // comment, and only the one inside the script actually matters.
  const notFound = path.join(outDir, "404.html");
  const nfHtml = (await readFile(notFound, "utf8")).replaceAll("__BASE__", siteUrl);
  await writeFile(notFound, nfHtml);

  await writeFile(path.join(outDir, ".nojekyll"), "");

  return { outDir, bundleBytes, wisp, siteUrl };
}

const invokedAsScript =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (invokedAsScript) {
  try {
    const outDir = process.argv[2] ? path.resolve(process.argv[2]) : DEFAULT_OUT_DIR;
    const result = await build({ outDir });
    console.log(`Built ${result.outDir}`);
    console.log(`Engine bundles: ${(result.bundleBytes / 1024 / 1024).toFixed(2)} MiB`);
    console.log(`Wisp pool: ${result.wisp.join(", ")}`);
    if (result.siteUrl) console.log(`Site URL: ${result.siteUrl}`);
  } catch (err) {
    console.error(`Build failed: ${err.message}`);
    process.exitCode = 1;
  }
}
